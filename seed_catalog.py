    cat_by_sub = {}
    for cid, ctitle, cemoji, subs in CATEGORIES:
        for s in subs:
            cat_by_sub[s] = cid

    products = []
    for i, (slug, name, sub, price, old, emoji, weight, desc, bullets) in enumerate(P, start=1):
        cat = cat_by_sub[sub]
        products.append({
            "id": i,
            "slug": slug,
            "name": name,
            "category": cat,
            "subcategory": sub,
            "price": price,
            "oldPrice": None,  # скидки убраны: только честная цена
            "emoji": emoji,
            "weight": weight,
            "description": desc,
            "features": bullets,
            "stock": 100,
            "rating": round(4.4 + (i % 6) * 0.1, 1),
            "reviews": 12 + (i * 7) % 240,
            "badge": None,
            "variants": ({"futbolki-5": [{"label": s, "stock": 100} for s in ["S", "M", "L", "XL", "XXL"]],
                          "futbolka-oversize": [{"label": s, "stock": 100} for s in ["M", "L", "XL"]]}).get(slug),
        })

    data = {
        "categories": [{"id": c, "title": t, "emoji": e, "subcategories": subs} for c, t, e, subs in CATEGORIES],
        "subcategories": SUBCATS,
        "products": products,
    }
    path = os.path.join(BASE, "data", "catalog.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
    print(f"готово: {len(products)} товаров -> {path}")


